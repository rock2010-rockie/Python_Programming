# 1. 기본 함수
# ===========================================================


def add(a, b):
    """a + b의 결과를 호출한다."""
    return a + b  # __add__() 호출 ex) int.__add__ , str.__add__ , tuple.__add__


print(add(3, 4))
print(add("hello", " python"))
print(add([1, 2], [3, 4]))
print(add((1, 2), (3, 4)))
print(add.__doc__)

